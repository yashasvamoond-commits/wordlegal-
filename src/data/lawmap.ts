const rule = (
  oldAct: RuleRef['oldAct'],
  newAct: RuleRef['newAct'],
  rows: [string, string, string, string, string?][],
): RuleRef[] =>
  rows.map(([oldSec, newSec, hi, en, note]) => ({ oldAct, newAct, oldSec, newSec, hi, en, note }))

export const LAW_MAP: RuleRef[] = [...rule('IPC', 'BNS', ipc), ...rule('CrPC', 'BNSS', crpc), ...rule('IEA', 'BSA', iea)]

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9().]/g, '')

export function lookupSection(q: string): RuleRef[] {
  const s = norm(q)
  if (!s) return LAW_MAP
  return LAW_MAP.filter((r) => {
    const hay = [
      r.oldAct, r.oldSec, r.newAct, r.newSec, r.hi, r.en, r.note ?? '',
      r.oldAct + r.oldSec, r.newAct + r.newSec, r.oldAct + ' ' + r.oldSec, r.newAct + ' ' + r.newSec,
      'section' + r.oldSec, 'section' + r.newSec, 'धारा' + r.oldSec, 'धारा' + r.newSec,
    ].join(' ')
    const key = norm(hay)
    return key.includes(s) || hay.toLowerCase().includes(q.toLowerCase())
  })
}

