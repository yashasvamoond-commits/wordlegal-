const DICT_SET = new Set(DICT_WORDS.map((d) => d.n))

function lev(a: string, b: string, max: number): number {
  if (Math.abs(a.length - b.length) > max) return max + 1
  const m = a.length
  const n = b.length
  let prev = new Array(n + 1)
  let cur = new Array(n + 1)
  for (let j = 0; j <= n; j++) prev[j] = j
  for (let i = 1; i <= m; i++) {
    cur[0] = i
    let rowMin = cur[0]
    for (let j = 1; j <= n; j++) {
      cur[j] = Math.min(
        prev[j] + 1,
        cur[j - 1] + 1,
        prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1),
      )
      if (cur[j] < rowMin) rowMin = cur[j]
    }
    if (rowMin > max) return max + 1
    const t = prev
    prev = cur
    cur = t
  }
  return prev[n]
}

const WORD_RE = /[\u0900-\u097F][\u0900-\u097F\u200d\u093c]*|[A-Za-z][A-Za-z'’-]*/g

export interface CheckOptions {
  nearMiss?: boolean
  english?: boolean
  punctuation?: boolean
}

/** पूरे पाठ की जाँच — प्रत्येक सुझाव के साथ स्थान (index/length) */
export function checkText(text: string, opts: CheckOptions = {}): Issue[] {
  const { nearMiss = true, english = true, punctuation = true } = opts
  const issues: Issue[] = []
  let n = 0
  const push = (i: Omit<Issue, 'id'>) => {
    if (issues.length > 300) return
    issues.push({ ...i, id: 'i' + n++ })
  }

  /* 1. बहु-शब्द अनौपचारिक प्रयोग (पहले लंबे वाक्यांश) */
  const formalSorted = [...FORMAL].sort((a, b) => b[0].length - a[0].length)
  const used: [number, number][] = []
  const overlaps = (s: number, e: number) => used.some(([a, b]) => s < b && e > a)
  for (const [bad, good, reason] of formalSorted) {
    if (bad === good) continue
    const re = new RegExp(bad.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi')
    let m: RegExpExecArray | null
    while ((m = re.exec(text))) {
      const s = m.index
      const e = s + m[0].length
      if (overlaps(s, e)) continue
      used.push([s, e])
      push({
        kind: 'formal', word: m[0], suggestion: good, reason, index: s, length: m[0].length,
      })
    }
  }

  /* 2. अंग्रेज़ी शब्द → हिन्दी पर्याय */
  if (english) {
    for (const m of text.matchAll(WORD_RE)) {
      const w = m[0]
      if (!/^[A-Za-z]/.test(w)) continue
      const hi = engByKey.get(w.toLowerCase())
      if (!hi) continue
      const s = m.index ?? 0
      if (overlaps(s, s + w.length)) continue
      used.push([s, s + w.length])
      push({
        kind: 'english', word: w, suggestion: hi,
        reason: 'हिन्दी न्यायालयीन लेखन में हिन्दी पारिभाषिक शब्द श्रेयस्कर है।',
        index: s, length: w.length,
      })
    }
  }

  /* 3. दोहरा स्थान, अनुचित विराम */
  if (punctuation) {
    for (const m of text.matchAll(/ {2,}/g)) {
      push({ kind: 'punct', word: '  ', suggestion: ' ', reason: 'अतिरिक्त स्थान हटाएँ।', index: m.index ?? 0, length: m[0].length })
      if (issues.length > 300) break
    }
    for (const m of text.matchAll(/\s+([,;:।])/g)) {
      push({ kind: 'punct', word: m[0], suggestion: m[1], reason: 'विराम-चिह्न से पूर्व स्थान नहीं होता।', index: m.index ?? 0, length: m[0].length })
      if (issues.length > 300) break
    }
    for (const m of text.matchAll(/([।!?])\1+/g)) {
      push({ kind: 'punct', word: m[0], suggestion: m[1], reason: 'विराम-चिह्न दोहराया गया है।', index: m.index ?? 0, length: m[0].length })
      if (issues.length > 300) break
    }
    for (const m of text.matchAll(/(\S+) \1\b/g)) {
      push({ kind: 'punct', word: m[0], suggestion: m[1], reason: 'शब्द दो बार लिखा गया है।', index: m.index ?? 0, length: m[0].length })
      if (issues.length > 300) break
    }
  }

  /* 4. शब्दकोश के निकटवर्ती (संभावित अशुद्ध) शब्द */
  if (nearMiss) {
    for (const m of text.matchAll(WORD_RE)) {
      const w = m[0]
      if (!/^[\u0900-\u097F]/.test(w) || w.length < 4) continue
      const s = m.index ?? 0
      if (overlaps(s, s + w.length)) continue
      const nw = norm(w)
      if (!nw || DICT_SET.has(nw)) continue
      /* रूप-भेद (बहुवचन/विभक्ति) को छोड़ें */
      let best: { w: string; d: number } | null = null
      const cands = [
        ...(BY_FIRST.get(nw.slice(0, 2)) ?? []),
        ...(BY_FIRST.get(nw.slice(0, 1) + nw.slice(1, 2)) ?? []),
      ]
      for (const c of cands) {
        if (Math.abs(c.n.length - nw.length) > 2) continue
        if (c.n.startsWith(nw) || nw.startsWith(c.n)) continue
        const d = lev(nw, c.n, 2)
        if (d <= 2 && (!best || d < best.d)) best = { w: c.w, d }
      }
      if (best && best.d <= 2) {
        push({
          kind: 'near', word: w, suggestion: best.w,
          reason: `शब्दकोश में निकटतम प्रविष्टि "${best.w}" है — वर्तनी जाँचें।`,
          index: s, length: w.length,
        })
      }
      if (issues.length > 300) break
    }
  }

  return issues.sort((a, b) => a.index - b.index)
}

