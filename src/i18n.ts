export type StrKey = keyof typeof STR

let currentLang: Lang = 'en'
const listeners = new Set<() => void>()

export function getLang(): Lang {
  return currentLang
}

export function setLang(l: Lang) {
  if (l === currentLang) return
  currentLang = l
  try {
    document.documentElement.lang = l === 'hi' ? 'hi' : 'en'
  } catch { /* noop */ }
  listeners.forEach((fn) => fn())
}

export function subscribeLang(fn: () => void): () => void {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

/** अनुवाद — {n} जैसे प्लेसहोल्डर भरता है */
export function tt(key: StrKey, lang: Lang = currentLang, vars?: Record<string, string | number>): string {
  const pair = STR[key] as Pair | undefined
  let s = pair ? pair[lang === 'hi' ? 1 : 0] : String(key)
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  }
  return s
}

/** डेटा-श्रेणी (हिन्दी) → UI नाम */
export function catName(hi: string, lang: Lang = currentLang): string {
  const key = `cat.${hi}` as StrKey
  return key in STR ? tt(key, lang) : hi
}

